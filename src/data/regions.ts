/** "지역명|도명" 형태의 고유 키 */
export function cityKey(city: City): string {
  return `${city.name}|${city.region ?? ''}`;
}

export function findCityByKey(key: string): City | null {
  for (const p of PROVINCES) {
    for (const city of p.cities) {
      if (cityKey(city) === key) return city;
    }
  }
  return null;
}
